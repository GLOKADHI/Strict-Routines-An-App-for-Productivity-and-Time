"""Generate Android constants from the canonical policy. --check detects drift."""
from pathlib import Path
import json
import sys

ROOT=Path(__file__).resolve().parents[1]
policy=json.loads((ROOT/'shared/product_policy.json').read_text())
gym=policy['gym']
fields={
    'GYM_START_HOUR':gym['activation_start_hour'],'GYM_CUTOFF_HOUR':gym['cutoff_hour'],
    'GYM_CUTOFF_MINUTE':gym['cutoff_minute'],'GYM_MAX_LIVES':gym['max_lives'],
    'GYM_WORKOUT_MINUTES':gym['default_workout_minutes'],'GYM_PROOF_MINUTES':gym['proof_window_minutes'],
    'GYM_MUSIC_DURATION_MS':str(gym['music_duration_seconds']*1000)+'L',
    'GYM_STATUS_LEASE_MS':str(gym['status_lease_seconds']*1000)+'L',
}
fields['BATH_POINTS_PER_OCCURRENCE']=policy['bath']['points_per_occurrence']
fields['BATH_RESERVATION_MINUTES']=policy['bath']['reservation_minutes']
for index,plan in enumerate(policy['bath']['college'],1):
    for name,key in [('START','window_start'),('END','window_end'),('PLANNED','planned_time')]:fields[f'BATH_COLLEGE_{index}_{name}']=json.dumps(plan[key])
for name,key in [('START','window_start'),('END','window_end'),('PLANNED','planned_time')]:fields[f'BATH_HOME_{name}']=json.dumps(policy['bath']['home'][key])
content='package com.strictrecords.app\n\n// Generated by scripts/generate_product_policy.py; edit shared/product_policy.json.\nobject ProductPolicy {\n'
content+='    const val VERSION = '+json.dumps(policy['version'])+'\n'
for key,value in fields.items():content+='    const val '+key+' = '+str(value)+'\n'
content+='    val GYM_WORKOUT_DURATIONS = listOf('+', '.join(map(str,gym['supported_workout_minutes']))+')\n}\n'
target=ROOT/'android/app/src/main/java/com/strictrecords/app/ProductPolicy.kt'
if '--check' in sys.argv:
    assert target.read_text(encoding='utf-8')==content,'Android product policy is stale; regenerate it'
else:target.write_text(content,encoding='utf-8')
